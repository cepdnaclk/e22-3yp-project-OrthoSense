"""
OrthoSense TinyML Model Training & TFLite Micro C-Array Conversion Pipeline
Trains a lightweight Neural Network for classifying rehabilitation gait phases
and converts it into an optimized C header array (model_data.h) for ESP32-S3.
"""

import os
import numpy as np

def generate_c_array(tflite_model_bytes: bytes, output_header_path: str, variable_name: str = "orthosense_model_data"):
    """Converts a raw TFLite model byte stream into a C array header file."""
    os.makedirs(os.path.dirname(output_header_path), exist_ok=True)
    hex_lines = []
    for i in range(0, len(tflite_model_bytes), 12):
        chunk = tflite_model_bytes[i:i+12]
        hex_lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

    content = f"""// Auto-generated by train_rehab_classifier.py
// TinyML Model byte array for ESP32-S3 TensorFlow Lite Micro
#ifndef ORTHOSENSE_MODEL_DATA_H
#define ORTHOSENSE_MODEL_DATA_H

#include <stdint.h>

const unsigned int {variable_name}_len = {len(tflite_model_bytes)};
const unsigned char {variable_name}[] __attribute__((aligned(16))) = {{
{chr(10).join(hex_lines)}
}};

#endif // ORTHOSENSE_MODEL_DATA_H
"""
    with open(output_header_path, "w") as f:
        f.write(content)
    print(f"[TinyML] Successfully exported C array to: {output_header_path} ({len(tflite_model_bytes)} bytes)")

def main():
    print("==================================================")
    print("OrthoSense TinyML Pipeline: Training & Conversion")
    print("==================================================")
    print("Features: 8 inputs (3x Accel, 3x Gyro, Flexion Angle, Pressure)")
    print("Classes: 4 outputs (NORMAL_GAIT, FLEXION, EXTENSION, ABNORMAL_LOAD)")
    
    # Target path for exported model header used by firmware
    output_header = os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "..", "firmware", "include", "model_data.h")
    )
    
    # Placeholder representative dummy bytes for initial skeleton
    dummy_model_bytes = bytes([0x1C, 0x00, 0x00, 0x00, 0x54, 0x46, 0x4C, 0x33] + [0x00] * 56)
    generate_c_array(dummy_model_bytes, output_header)

if __name__ == "__main__":
    main()
